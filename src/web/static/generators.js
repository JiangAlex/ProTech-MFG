python.forBlock['iperf_client'] = function(block) {
  var target = block.getFieldValue('TARGET');
  var port = block.getFieldValue('PORT');
  var duration = block.getFieldValue('DURATION');
  var bind = block.getFieldValue('BIND');
  var cmd = 'result = subprocess.run(["iperf3", "-c", "' + target + '", "-p", "' + port + '", "-t", "' + duration + '"';
  if (bind) cmd += ', "-B", "' + bind + '"';
  cmd += ', "-J"], capture_output=True, text=True, timeout=' + (parseInt(duration) + 10) + ')\n';
  return cmd;
};

