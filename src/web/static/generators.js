// === Generate complete test file ===

function generateTestFile(workspace) {
  var name = document.getElementById('test-name').value || 'GUI-001';
  // Pure MFG: the dev-type selector was removed, so default to 'mfg'. Guard
  // against the missing element (reading .value of null threw a TypeError that
  // silently aborted saveTest -> nothing saved, no alert).
  var devType = (document.getElementById('dev-type') || {}).value || 'mfg';
  var devModel = (document.getElementById('dev-model') || {}).value || '';
  var blockCode = python.workspaceToCode(workspace);

  if (!blockCode.trim()) {
    return '# 拖拉積木到工作區以產生測試程式碼';
  }

  if (devType === 'mfg') {
    // Manufacturing script template. Block code goes INSIDE `try:` under
    // `def run(self):`, so it needs 12 spaces of indentation. Generators emit
    // bare statements (e.g. "self.enter_uboot_menu()").
    //
    // Some blocks (message, verify_*, band_*, etc.) were authored for the old
    // WLAN fluent template and emit a chained continuation like
    // "    .message(\"PASS\")\n". Dropped into the MFG template as-is, that
    // becomes a lone indented ".method()" line -> SyntaxError: unexpected
    // indent. Normalize any such continuation line to a bare "self.method()"
    // statement here, at the single assembly choke point, so every block
    // produces valid Python regardless of whether its generator added an MFG
    // branch.
    var mfgCode = blockCode.replace(/^[ \t]*\.([A-Za-z_]\w*\()/gm, 'self.$1');
    var indent = mfgCode.replace(/^(?=.)/gm, '            ');
    var code = '"""Auto-generated by WLAN Test GUI."""\n'
      + 'import time\n'
      + 'from mfg.manufacturing_script import ManufacturingScript\n'
      + '\n\n'
      + 'class TestCase(ManufacturingScript):\n'
      + '    tc_id = "' + name + '"\n'
      + '    headline = "' + name + '"\n'
      + '    purpose = "Auto-generated manufacturing test"\n'
      + '\n'
      + '    def run(self):\n'
      + '        try:\n'
      + indent
      + '            self.message("PASS")\n'
      + '        finally:\n'
      + '            self.cleanup()\n';
    return code;
  }

  var code = '"""Auto-generated by WLAN Test GUI."""\n'
    + 'from src.wlan.blocks import Block\n'
    + 'from src.wlan.wlan_script import WlanScript\n'
    + '\n\n'
    + 'class TestCase(WlanScript):\n'
    + '    tc_id = "' + name + '"\n'
    + '    headline = "' + name + '"\n'
    + '    device_type = "' + devType + '"\n';
  if (devModel) code += '    device_model = "' + devModel + '"\n';
  code += '\n'
    + '    def run(self):\n'
    + '        Block(self) \\\n'
    + blockCode;
  return code;
}

