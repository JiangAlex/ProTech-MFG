// === Utility generators ===

python.forBlock['wait_seconds'] = function(block) {
  var sec = block.getFieldValue('SECONDS');
  // The MFG template emits plain statements (indented later), while the
  // WLAN/SW template uses a fluent Block(self).chain(). Emit the form that
  // matches the currently selected device type so the block works in both.
  var devType = (document.getElementById('dev-type') || {}).value || '';
  if (devType === 'mfg') {
    return 'time.sleep(' + sec + ')\n';
  }
  return '    .wait(' + sec + ')\n';
};

python.forBlock['message'] = function(block) {
  var text = block.getFieldValue('TEXT');
  // The MFG template emits plain statements (indented later); the WLAN/SW
  // template uses a fluent Block(self).chain(). `message` is the only block in
  // the MFG toolbox that still defaulted to the fluent form, which produced a
  // lone indented ".message(...)" line -> SyntaxError. Emit the form matching
  // the selected device type (mirrors wait_seconds).
  var devType = (document.getElementById('dev-type') || {}).value || '';
  if (devType === 'mfg') {
    return 'self.message("' + text + '")\n';
  }
  return '    .message("' + text + '")\n';
};

python.forBlock['pdu_power_cycle'] = function(block) {
  // BARE statement for the MFG template: control the DUT DC Jack via the
  // FT232H relay. ACTION selects ON / OFF / power-cycle (OFF -> wait -> ON).
  // DELAY (seconds) is the OFF duration, only used for CYCLE.
  var action = block.getFieldValue('ACTION');
  if (action === 'ON')  return 'self.dcjack_on()\n';
  if (action === 'OFF') return 'self.dcjack_off()\n';
  var delay = block.getFieldValue('DELAY');
  return 'self.dcjack_power_cycle(off_delay=' + delay + ')\n';  // CYCLE (default)
};

